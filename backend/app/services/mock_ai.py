T = TypeVar("T", bound=BaseModel)

_TITLE_RE = re.compile(r"CHAPTER TITLE:\s*(.+)")
_COURSE_RE = re.compile(r"COURSE TITLE:\s*(.+)")
_KIND_RE = re.compile(r"TEMPLATE KIND:\s*(\w+)")
_TOC_RE = re.compile(r"^\s*\d+\.\s*(.+)$", re.MULTILINE)
_BLOCK_ID_RE = re.compile(r"block_[0-9a-f]{6,}")

_LOREM = (
    "This section explains the idea in practical terms and connects it back to the "
    "learner's day-to-day work. Placeholder prose generated by the offline mock "
    "client so that pagination, styling and export can be validated without "
    "calling a language model. "
)


def _line(pattern: re.Pattern[str], text: str, default: str = "") -> str:
    match = pattern.search(text or "")
    return match.group(1).strip() if match else default


class MockAIClient(AIClient):
    is_mock = True

    def __init__(self, settings: Settings | None = None) -> None:
        self.settings = settings or get_settings()
        self.calls: list[dict[str, Any]] = []

    # --- shared plumbing --------------------------------------------------
    async def _simulate(self, kind: str, purpose: str) -> float:
        """Optional latency + metrics so concurrency can be measured offline."""
        started = time.perf_counter()
        metrics = current_metrics()
        if metrics:
            metrics.call_started()
        delay = self.settings.mock_latency_ms / 1000
        if delay:
            await asyncio.sleep(delay)
        if metrics:
            metrics.call_finished()
            metrics.record_call(
                CallRecord(
                    kind=kind,
                    purpose=purpose or kind,
                    model="mock",
                    seconds=time.perf_counter() - started,
                )
            )
        return started

    # --- AIClient ---------------------------------------------------------
    async def structured(
        self,
        *,
        schema: type[T],
        system: str,
        user: str,
        model: str | None = None,
        purpose: str = "",
        phase: str = "default",
        max_output_tokens: int | None = None,
        on_delta: StreamSink | None = None,
    ) -> T:
        self.calls.append({"kind": "structured", "schema": schema.__name__, "purpose": purpose})
        await self._simulate("structured", purpose or schema.__name__)
        builder = _BUILDERS.get(schema.__name__)
        payload = builder(user) if builder else {}
        if on_delta is not None:
            # Deliver the same real (deterministic mock) payload in chunks
            # instead of one shot, so the streaming code path is exercised
            # offline too - not fabricated content, just paced delivery of
            # what would be returned anyway.
            on_delta.reset()
            raw = json.dumps(payload, ensure_ascii=False)
            chunk_size = 24
            for start in range(0, len(raw), chunk_size):
                on_delta.append(raw[start : start + chunk_size])
                # A cooperative yield, not a delay (sleep(0) adds no wall-clock
                # time) - without it this loop never gives the event loop a
                # chance to forward each chunk to an SSE subscriber before the
                # whole payload is already done.
                await asyncio.sleep(0)
        return schema.model_validate(payload)

    async def research(
        self,
        *,
        prompt: str,
        deep: bool = False,
        system: str = "",
        schema: type[BaseModel] | None = None,
        phase: str = "research",
    ) -> ResearchResult:
        self.calls.append({"kind": "research", "deep": deep, "structured": schema is not None})
        await self._simulate("research", "research")
        title = _line(_TITLE_RE, prompt, "the chapter topic")
        # Mirror the real client: when a schema is requested the single call can
        # return the structured payload directly.
        payload = None
        if schema is not None and self.settings.single_call_research:
            builder = _BUILDERS.get(schema.__name__)
            if builder:
                payload = builder(prompt)
        return ResearchResult(
            text=(
                f"Mock research notes for '{title}'.\n"
                "- Definition, mechanism and typical use cases.\n"
                "- Two illustrative examples and one documented case.\n"
                "- Frequent mistakes and current best practice.\n"
            ),
            citations=[{"title": "Mock reference", "url": "https://example.com/mock"}],
            model="mock",
            mode="mock",
            structured=payload,
        )

    async def image(
        self, *, prompt: str, size: str | None = None, phase: str = "image"
    ) -> bytes:
        self.calls.append({"kind": "image"})
        await self._simulate("image", "image")
        return _placeholder_png(prompt, size or self.settings.image_size)


