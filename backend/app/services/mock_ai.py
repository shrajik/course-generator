"""Deterministic offline AI client.

Used when `MOCK_OPENAI=true` or no API key is configured. It returns
schema-valid, structurally realistic payloads so the *whole* pipeline - planner,
research, writer, reviewer, document assembly, image generation, patch editing
and PDF export - can be exercised end to end without network access.

The content is obviously placeholder text. It is never used when a real key is
present unless MOCK_OPENAI is explicitly set.
"""

from __future__ import annotations

