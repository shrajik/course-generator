def _planner_output(user: str) -> dict[str, Any]:
    course = _line(_COURSE_RE, user, "Untitled Course")
    titles = _TOC_RE.findall(user) or ["Chapter One", "Chapter Two"]
    chapters = []
    for index, title in enumerate(titles, start=1):
        chapters.append(
            {
                "id": f"chapter_{index}",
                "title": title,
                "order": index,
                "objective": f"Understand and apply the core ideas of {title}.",
                "summary": f"An overview of {title} for the stated audience.",
                "sections": [
                    {
                        "title": "Core ideas",
                        "summary": f"The essentials of {title}.",
                        "key_points": ["Definition", "Mechanism", "Application"],
                    },
                    {
                        "title": "In practice",
                        "summary": "How this shows up in real work.",
                        "key_points": ["Worked example", "Pitfalls"],
                    },
                ],
                "required_blocks": ["heading", "paragraph", "summary", "quiz"],
                "optional_blocks": ["image", "table", "tip"],
                "key_concepts": [f"{title} fundamentals", "Practical trade-offs"],
                "prerequisites": [] if index == 1 else [titles[index - 2]],
                "research_questions": [
                    f"What is {title} and why does it matter?",
                    f"What mistakes do people make with {title}?",
                ],
                "estimated_words": 1400,
                "difficulty": "beginner" if index == 1 else "intermediate",
            }
        )
    return {
        "course_summary": f"A practical course covering {course}.",
        "learning_objectives": [
            f"Explain the core concepts behind {course}.",
            "Apply the material to a realistic scenario.",
            "Avoid the most common mistakes.",
        ],
        "prerequisites": ["Curiosity", "Basic familiarity with the subject area"],
        "tone": "clear, practical, encouraging",
        "chapters": chapters,
        "critique": {
            "missing_concepts": ["A short glossary chapter could help beginners"],
            "duplicate_topics": [],
            "ordering_issues": [],
            "learning_progression_notes": (
                "Progression looks reasonable: foundations first, application later."
            ),
            "suggested_toc": titles,
        },
    }


